// GetCharacterWuxing 获取汉字五行
// 先查覆盖表（字义法优先），再按部首映射表推算
func GetCharacterWuxing(char string) string {
	// 1. 先查覆盖表
	if wx, ok := CharacterWuxingOverride[char]; ok {
		return wx
	}

	// 2. 查部首映射表
	if data, ok := HanziData[char]; ok {
		if wx := GetWuxingByRadical(data.Radical); wx != "" {
			return wx
		}
	}

	return ""
}
