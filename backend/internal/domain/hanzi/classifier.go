// buildOverrideMap 构建分类倒排索引 char → categories
func buildOverrideMap() map[string][]string {
	m := make(map[string][]string)
	for _, entry := range characterCategoryList {
		for _, r := range []rune(entry.chars) {
			ch := string(r)
			// 去重
			found := false
			for _, c := range m[ch] {
				if c == entry.cat {
					found = true
					break
				}
			}
			if !found {
				m[ch] = append(m[ch], entry.cat)
			}
		}
	}
	return m
}

// ClassifyNaming 对单个汉字进行起名分类标注
//
// 优先级：
//   1. 策展覆盖表 characterCategoryOverride
//   2. 部首映射 radicalCategoryMap
//   3. 字义关键词匹配 meaningCategoryPatterns
//   4. 五行兜底
func ClassifyNaming(char, radical, meaning, wuxing string) []string {
	// 优先级 1：策展覆盖表
	if cats, ok := characterCategoryOverride[char]; ok {
		return cats
	}

	var cats []string
	seen := make(map[string]bool)

	addCat := func(c string) {
		if !seen[c] {
			seen[c] = true
			cats = append(cats, c)
		}
	}

	// 优先级 2：部首映射
	if radical != "" {
		if radCats, ok := radicalCategoryMap[radical]; ok {
			for _, c := range radCats {
				addCat(c)
			}
		}
	}

	// 优先级 3：字义关键词匹配
	if meaning != "" {
		for _, pattern := range meaningCategoryPatterns {
			for _, kw := range pattern.keywords {
				if strings.Contains(meaning, kw) {
					addCat(pattern.cat)
					break
				}
			}
		}
	}

	// 优先级 4：五行兜底
	if len(cats) == 0 && wuxing != "" {
		switch wuxing {
		case "水":
			cats = append(cats, "清新水韵")
		case "木":
			cats = append(cats, "花木")
		case "火":
			cats = append(cats, "光明")
		case "金":
			cats = append(cats, "美玉")
		case "土":
			cats = append(cats, "山水")
		}
	}

	return cats
}

// GetNamingCategories 获取汉字的所有起名分类标签
func GetNamingCategories(char string) []string {
	h, ok := HanziData[char]
	if !ok {
		return nil
	}
	return h.NamingCategories
}

// IsCuratedNamingChar 判断某字是否在人工策展起名用字覆盖表中
//
// 注意：与 GetNamingCategories（可能被自动分类/五行兜底污染，荒谬字如"贪"水→"清新水韵"
// 也会获分类）不同，本表是 17 个起名分类的人工精选字（characterCategoryList，约 446 字）。
// verify_fate 复测验证：经典好字（毅/辉/涛/英/琳/雅/梅/强/凯）8/12 在表内，
// 荒谬字（贪/疟/骂/吠/靶/振/凑/递等）21/22 不在表内——是荒谬字与好字的强区分信号。
func IsCuratedNamingChar(char string) bool {
	_, ok := characterCategoryOverride[char]
	return ok
}

// init 构建策展覆盖表倒排索引，供 ClassifyNaming 优先使用
func init() {
	characterCategoryOverride = buildOverrideMap()
}
