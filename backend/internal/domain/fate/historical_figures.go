// IsHistoricalFigureCombo 判断两字组合是否为历史人物字/号专名（正反序均检测）
// 用于双名候选生成时剔除「仲尼」「尼仲」等与历史人物撞车的组合
func IsHistoricalFigureCombo(c1, c2 string) bool {
	if c1 == "" || c2 == "" {
		return false
	}
	if historicalFigureCombos[c1+c2] {
		return true
	}
	return historicalFigureCombos[c2+c1]
}