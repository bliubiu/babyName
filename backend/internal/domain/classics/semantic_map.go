// SynonymMap 近义/同义字映射表
// 用于诗句语义匹配增强：名字含字A但诗词中出现的近义字B，也视为语义匹配
// key=字, value=近义字列表（双向映射，含自身）
var SynonymMap = buildSynonymMap()

// FindSemanticChars 查找某字的近义字集合（含自身）
// 用于扩展诗词匹配的查询范围
func FindSemanticChars(char string) []string {
	// 始终包含自身
	result := []string{char}
	if synonyms, ok := SynonymMap[char]; ok {
		// 去重合并
		seen := map[string]bool{char: true}
		for _, s := range synonyms {
			if !seen[s] {
				seen[s] = true
				result = append(result, s)
			}
		}
	}
	return result
}

